from pathlib import Path
import re

JAVA = Path('app/src/main/java/com/rgapro1/ocaso/MainActivity.java')
s = JAVA.read_text(encoding='utf-8')
changed = False


def normalize_java_escapes(line):
    """Remove accidental Markdown escapes while preserving real Java string escapes."""
    out = []
    i = 0
    in_string = False
    in_char = False
    while i < len(line):
        c = line[i]
        if c == '\\':
            j = i
            while j < len(line) and line[j] == '\\':
                j += 1
            run = line[i:j]
            nxt = line[j] if j < len(line) else ''
            punctuation = ':<>_%.,'
            if nxt in punctuation and (nxt != '.' or not in_string):
                out.append(nxt)
                i = j + 1
                continue
            out.append(run)
            if nxt in ('"', "'"):
                if nxt == '"' and in_string and len(run) % 2 == 1:
                    out.append(nxt)
                    i = j + 1
                    continue
                if nxt == "'" and in_char and len(run) % 2 == 1:
                    out.append(nxt)
                    i = j + 1
                    continue
            i = j
            continue
        out.append(c)
        if c == '"' and not in_char:
            in_string = not in_string
        elif c == "'" and not in_string:
            in_char = not in_char
        i += 1
    return ''.join(out)


lines = s.splitlines()
for i, line in enumerate(lines):
    normalized = normalize_java_escapes(line)
    if normalized != line:
        lines[i] = normalized
        changed = True

    stripped = lines[i].strip()
    if stripped.startswith('refresh[0]=()->{') and stripped.endswith('}}'):
        lines[i] = lines[i] + ';'
        changed = True

# These two generated helpers are the only places where a local JSONArray named
# `out` is required. Do not infer this from arbitrary uses of `out`: several
# unrelated helpers use StringBuilder/ArrayList variables with that name.
s = '\n'.join(lines) + ('\n' if s.endswith('\n') else '')

exact_out_markers = [
    ('if(block.trim().isEmpty())return out;', '        JSONArray out=new JSONArray();\n        '),
    ('for(String line:block.split("\\\\n|;")){String x=line.trim();', '        JSONArray out=new JSONArray();\n        '),
]
for marker, prefix in exact_out_markers:
    if marker in s:
        # Only add if the surrounding method does not already declare `out`.
        pos = s.find(marker)
        method_start = s.rfind('    private ', 0, pos)
        method_end = s.find('{', method_start)
        if method_start >= 0 and method_end >= 0:
            body_prefix = s[method_end:pos]
            if 'JSONArray out=new JSONArray();' not in body_prefix:
                s = s[:method_end + 1] + '\n        JSONArray out=new JSONArray();' + s[method_end + 1:]
                changed = True

# Remove the declaration accidentally inserted by older versions of this script
# into helpers that already receive `out` or need a different collection type.
s = s.replace('private void appendSearchJson(StringBuilder out,JSONObject o){JSONArray out=new JSONArray();', 'private void appendSearchJson(StringBuilder out,JSONObject o){')
s = s.replace('private void appendSearchArray(StringBuilder out,JSONArray a){JSONArray out=new JSONArray();', 'private void appendSearchArray(StringBuilder out,JSONArray a){')

# The OCR parser generated by the document pipeline uses `block`; an older patch
# emitted the normalized split expression with an undeclared `raw` local.
s = re.sub(
    r'(?m)^(\s*)String\[\] lines=\(raw==null\?"":raw\.replace\("\\\\r","\\\\n"\)\)\.split\("\\\\n"\);$',
    r'\1String[] lines=(block==null?"":block.replace("\\r","\\n")).split("\\n");',
    s,
)

# onActivityResult cannot access the birth EditText created inside showOcrResult.
bad_birth = 'if(dniMode&&birth!=null)birth.setVisibility(View.VISIBLE);else processLastImage(false);'
if bad_birth in s:
    s = s.replace(bad_birth, 'processLastImage(false);')
    changed = True

